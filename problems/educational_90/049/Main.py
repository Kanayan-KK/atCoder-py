# 【問題】
# E869120 君は、長さ N のビット列 S を持っています。最初、S の全ての文字は 0 です。
#
# ABC 商店には M 個のアイテムが売られており、1 から M までの番号がついています。アイテム i
# の価格は C[i] で、これを使うと、
# S の L[i] ~ R[i] 文字目が反転します。すなわち、S の L[i] ~ R[i] 文字目のうち、0 であったものは 1
# に、
# 1 であったものは 0 に変化します。
#
# E869120 君は、M 個のアイテムのいくつかを選んで買うことで、次の条件が満たされるようにしたいです。
#
# ・条件 : 長さ N の任意のビット列 T （全部で 2^N 通りあります）に対して、「買ったアイテムから一つ
# を選んで使う」行為を好きな回数（$0$ 回でもよい）することで、S を T
# に一致させることができる。
#
# 条件を満たすために、E869120 君が買う必要のあるアイテムの合計額の最小値を求めてください。
#
# ただし、全てのアイテムを買っても条件を満たせない場合は、その旨を報告してください。
#
# 【制約】
# ・1 ≦ N ≦ 10^5
# ・1 ≦ M ≦ 10^5
# ・1 ≦ C[i] ≦ 10^9
# ・1 ≦ L[i] ≦ R[i] ≦ N
# ・入力は全て整数
#
# 【入出力形式】
# 入力形式
# N M
# C[1] L[1] R[1]
# C[2] L[2] R[2]
#  :
# C[M] L[M] R[M]
#
