# 【制約】
# ・1 ≦ N ≦ 10^18
# ・2 ≦ B ≦ 1000
# ・1 ≦ K ≦ 9
# ・1 ≦ c[1] < c[2] < c[3] < ... < c[K] ≦ 9
# ・入力はすべて整数
#
# 【入出力形式】
# 入力形式
# N B K
# c[1] c[2] c[3] ... c[K]
