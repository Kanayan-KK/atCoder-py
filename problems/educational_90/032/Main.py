# 【問題】
# ABC 陸上部には N 人の駅伝選手がいます。
# 駅伝では 1 人の選手が 1 つの区を担当して走ります。
# 複数の選手が 1 つの区を担当することや 1 人の選手が複数の区を担当することはできません。
# 駅伝コースは第 1 区から第 N 区まであり、選手 i が第 j 区を走るのにかかる時間は A[i][j] です。
#
# 駅伝は第 1 区、第 2 区、…、第 N 区の順にその区間を担当する選手が走ります。
# 第 j 区 (1 ≦ j ≦ N-1) を走り終わった選手は第 j+1 区を走る選手にタスキを渡さなければなりません。
# このとき、タスキの受け渡しにかかる時間は十分短いため無視できます。最後にタスキを受け取った選手が
# 第 N 区を走りゴールとなります。
#
# さて、ABC 陸上部には M 個の噂があります。i 番目の噂は 「選手 X[i] と Y[i] は仲が悪い」
# というものです。
# 噂をされている選手同士ではタスキの受け渡しができません。つまり、選手 X[i] の直後に選手 Y[i]
# が走ることも、選手 Y[i] の直後に選手 X[i] が走ることもできません。
#
# ABC 陸上部が駅伝をゴールするのにかかる時間の最小値を求めてください。
# ただし、どうやってもゴールできない場合、−1 と出力してください。
#
#
# 【制約】
# ・1 ≦ N ≦ 10
# ・1 ≦ A[i][j] ≦ 1000
# ・0 ≦ M ≦ N(N-1)/2
# ・1 ≦ X[i] < Y[i] ≦ N
# ・(X[i], Y[i]) ≠ (X[j], Y[j]) [i ≠ j]
# ・入力はすべて整数
#
# 【入出力形式】
# 入力形式
# N
# A[1][1] A[1][2] ... A[1][N]
# A[2][1] A[2][2] ... A[2][N]
#  :
# A[N][1] A[N][2] ... A[N][N]
# M
# X[1] Y[1]
# X[2] Y[2]
#  :
# X[M] Y[M]
