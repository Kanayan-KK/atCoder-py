# 【問題】
# デパートの高橋屋では N 日にわたって初売りが行われます。
# i 日目には A[i] 円の福袋 A と B[i] 円の福袋 B が売られます。
#
# 低橋くんは N 日間、毎日高橋屋で福袋 A か福袋 B のどちらかを購入します。
# N 日間で購入した N 個の福袋の総額が S 円になるような購入の方法が存在するかを判定し、存在するなら
# ばその一例を求めてください。
#
# 【出力形式】
# 存在する場合　｜N 文字の文字列 T を出力してください。文字列 T の i (1 ≦ i ≦ N) 文字目を T[i]
# とするとき、i 日目に福袋 A を購入する場合 T[i] =
# 'A'、福袋 B を購入する場合は T[i] = 'B' にしてください。
# 存在しない場合｜"Impossible" と出力してください。
#
# 【制約】
# ・1 ≦ N ≦ 100
# ・1 ≦ S ≦ 10^5
# ・1 ≦ A[i], B[i] ≦ 10^5 (1 ≦ i ≦ N)
# ・入力はすべて整数
#
# 【入出力形式】
# 入力形式
# N S
# A[1] B[1]
# A[2] B[2]
#  :
# A[N] B[N]
#
# 出力形式
# 存在する場合　｜N 文字の文字列 T を出力してください。文字列 T の i (1 ≦ i ≦ N) 文字目を T[i]
# とするとき、i 日目に福袋 A を購入する場合 T[i] =
# 'A'、福袋 B を購入する場合は T[i] = 'B' にしてください。
# 存在しない場合｜"Impossible" と出力してください。
#
