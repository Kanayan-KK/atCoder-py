# 【問題】
# N 個の白いボールと N 個のアイテムがあります。
# ボールとアイテムにはそれぞれ 1 から N までの番号がついています。
#
# ここで、アイテム i について以下のことがわかっています。
# ・ボール A[i], B[i] の少なくとも一方が白である時、またその時に限り使える。
# ・これを使うと、ボール i を黒く塗ることができる。
#
# N 個のアイテムを適切な順序で使うことで、全てのボールを黒く塗ることは可能でしょうか？
# 可能ならば、使う順序の一例を求めてください。
#
# 【制約】
# ・1 ≦ N ≦ 10^5
# ・1 ≦ A[i], B[i] ≦ N
# ・入力は全て整数
#
# 【入出力形式】
# 入力形式
# N
# A[1] B[1]
# A[2] B[2]
#  :
# A[N] B[N]
#
# 出力形式（X[1] → X[2] → ... → X[N] の順にアイテムを使う場合）
# X[1]
# X[2]
#  :
# X[N]
#
# 出力形式（すべてのボールを黒く塗ることが不可能な場合）
# -1
#
