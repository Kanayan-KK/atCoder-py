# 【問題】
# AtCoder 国には N 個の街があり、それぞれ 1,2,…,N と番号付けられています。任意の 2
# つの街の間には道路があり、交通費 （単位：スヌーク）
# を支払うことで一方の街から他方の街へ移動することができます。
#
# AtCoder 国の大臣は、最初に正の整数 X を決めた後、それぞれの (i, j) [i ≠ j]
# の組について交通費を以下のように設定することにしました。
# > A[i][j] ≠ -1 のとき：街 i と街 j の間を結ぶ道路の交通費は A[i][j] スヌーク
# > A[i][j] = -1 のとき :街 i と街 j の間を結ぶ道路の交通費は X スヌーク
#
# また、チョクダイ国王の意向により、以下の要件を満たさなければなりません。
# > 経路を適切に選ぶことで、街 i から街 j まで合計 P スヌーク以下で到達可能であるような
# > 組 (i, j) [1 ≦ i < j ≦ N] がちょうど K 個存在する。
#
# チョクダイ国王の意向を満たすような X の選び方はいくつ存在しますか。
# ただし、無限個の場合はそのことを報告してください。
#
# 【制約】
# ・2 ≦ N ≦ 40
# ・1 ≦ P ≦ 10^9
# ・0 ≦ K ≦ N(N-1)/2
# ・i ≠ j ならば 1 ≦ A[i][j] ≦ 10^8 または A[i][j]=-1
# ・i = j ならば A[i][j]=0
# ・A[i][j]=A[j][i]
# ・入力は全て整数
#
# 【入出力形式】
# 入力形式
# N P K
# A[1][1] ... A[1][N]
# ⋮
# A[N][1] ... A[N][N]
#
# 出力
# チョクダイ国王の意向を満たすような正整数 X の個数が有限個ならばその個数を、
# 無限個ならば `Infinity` と出力してください。
