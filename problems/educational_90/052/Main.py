# 【問題】
# N 個の 6 面体サイコロがあり、1, 2, 3, ..., N と番号付けられています。
# サイコロ i の j (1 ≦ j ≦ 6) 番目の面には整数 A[i][j] が書かれています
# ここで、それぞれのサイコロについて、書かれている整数は相異なります。
#
# さて、サイコロの出目に対して、次のように得点を定義します。
#
#         得点は N 個のサイコロの出目の総積である。
#         つまり、サイコロ i の出目を R[i] としたとき、得点は R[1]×R[2]×⋯×R[N] と計算される。
#
# N 個のサイコロの出目の結果としては 6^N 通り考えられますが、これら全てにおける得点の総和 S を
# 10^9+7 で割った余りを求めてください。
# ただし、それぞれのサイコロは互いに区別できるものとします。
#
# 【制約】
# ・1 ≦ N ≦ 100
# ・1 ≦ A[i][1] < A[i][2] < A[i][3] < A[i][4] < A[i][5] < A[i][6] ≦ 100
# ・入力はすべて整数である
#
# 【入出力形式】
# 入力形式
# N
# A[1][1] A[1][2] A[1][3] A[1][4] A[1][5] A[1][6]
#  :
# A[N][1] A[N][2] A[N][3] A[N][4] A[N][5] A[N][6]
