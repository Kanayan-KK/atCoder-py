# 【問題】
# ABC 競技プログラミング塾には N 個のクラスがあり、番号 i のクラスはレーティング A[i]
# の生徒を対象としています。
# 今、Q 人の生徒が入塾しようとしています。番号 j の生徒のレーティングは B[j]
# です。各生徒は自分に合わないレベルのクラスに行くと不満なので、不満度は次のように定義されます。
# ・対象レーティング X と自分のレーティング Y の差の絶対値、すなわち |X-Y|
# j = 1, 2, 3,..., Q それぞれについて、番号 j の生徒の不満度として考えられる最小値を求めてください
# 。
# ただし 1 人もいないクラス、複数人から成るクラスがあっても良いものとします。
#
# 【制約】
# ・1 ≦ N ≦ 10^5
# ・1 ≦ Q ≦ 10^5
# ・0 ≦ A[i] ≦ 10^9
# ・0 ≦ B[j] ≦ 10^9
# ・入力はすべて整数
#
# 【入出力形式】
# 入力形式
# N
# A[1] A[2] ... A[N]
# Q
# B[1]
# B[2]
# B[3]
#  :
# B[Q]
#
