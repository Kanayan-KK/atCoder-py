# 【問題】
# 日本を N 個の区画に分けます。西から i 個目の区画（以下、区画 i とする）の標高は A[i] です。
# これから Q 回の地殻変動が起こります。i 回目の地殻変動では、区画 L[i], L[i]+1, ..., R[i] の標高が
# V[i] ずつ変化します。（V[i]≧0 のとき標高が
# |V_i| 上がり、V_i<0 のとき標高が |V[i]| 下がることを意味します）
#
# さて、区画 1 から N へ行く際の不便さは次のように定義されます。
# > 区画 i の標高を E[i] とするとき、不便さは |E[1] - E[2]| + |E[2] - E[3]| + ... + |E[N-1] -
# E[N]|
#
# 各地殻変動後の不便さをそれぞれ求めてください。
#
# 【制約】
# ・1 ≦ N,Q ≦ 10^5
# ・-10^9 ≦ A[i], V[i] ≦ 10^9
# ・1 ≦ L ≦ R ≦ N
# ・入力は全て整数
#
# 【入出力形式】
# 入力形式
# N Q
# A[1] A[2] ... A[N]
# L[1] R[1] V[1]
# :
# L[2] R[2] V[2]
# L[Q] R[Q] V[Q]
#
# 出力形式
# Q 行出力してください。
# i 行目には、i 番目の地殻変動が終わった後の不便さを出力してください。
#
# 【サンプルテスト】解答を書いた後、リポジトリのルートで実行する。
