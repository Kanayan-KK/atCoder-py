# 【問題】
# N 頂点 M 辺の連結な単純無向グラフが与えられます。グラフの頂点は、それぞれ 1 から N
# までの番号が振られています。 i 番目の辺は、頂点 a[i] と b[i]
# を双方向に結んでいます。
#
# 10^9 種類の色があり、各色には 1 から 10^9 までの番号が振られています。最初、すべての頂点は色 1
# で塗られています。
#
# 以下の形式のクエリが Q 個与えられるので、順に処理してください。
#
# - 整数 x, y が与えられる。現在の頂点 x の色の番号を出力し、頂点 x
# とそれに隣接するすべての頂点を色 y で塗り替える。
#
#
# 【制約】
# ・1 ≦ N ≦ 2×10^5
# ・N-1 ≦ M ≦ min(N(N-1)/2, 2×10^5)
# ・1 ≦ a[i], b[i] ≦ N
# ・1 ≦ Q ≦ 2×10^5
# ・1 ≦ x ≦ N
# ・1 ≦ y ≦ 10^9
# ・与えられるグラフは単純グラフである
# ・与えられるグラフは連結
# ・入力はすべて整数
#
# 【小課題】
# 1. (2 点) N, Q ≦ 2000
# 2. (4 点) 追加の制約はない
#
# 【入出力形式】
# 入力形式
# N M
# a_1 b_1
# :
# a_M b_M
# Q
# x_1 y_1
# :
# x_Q y_Q
#
